  # 6. Training-fold IPCW and performance metrics ---------------------------------
  G <- function(km, times, left = FALSE, max_followup) {
    vapply(times, function(t) {
      if (!is.finite(t) || t < 0 || t > max_followup) return(NA_real_)
      idx <- if (left) sum(km$time < t) else sum(km$time <= t)
      if (!idx) 1 else as.numeric(km$surv[idx])
    }, numeric(1))
  }
  evaluate <- function(z, km, f) {
    max_follow <- max(d$OBS_Days[d$Outer_Fold != f])
    cases_tau <- which(z$Event == 1L & z$OBS_Days <= tau)
    g <- G(km, z$OBS_Days[cases_tau], TRUE, max_follow)
    den <- num <- 0
    if (length(cases_tau) && all(is.finite(g) & g > 0))
      for (k in seq_along(cases_tau)) {
        i <- cases_tau[k]
        j <- which(z$OBS_Days > z$OBS_Days[i])
        if (length(j)) {
          w <- 1 / g[k]^2
          num <- num + w * sum((z$Linear_Predictor[i] > z$Linear_Predictor[j]) +
                                 0.5 * (z$Linear_Predictor[i] == z$Linear_Predictor[j]))
          den <- den + w * length(j)
        }
      }
    uno <- if (length(cases_tau) && all(is.finite(g) & g > 0) &&
               is.finite(den) && den > 0) num / den else NA_real_
    out <- list(metric_row(f, "Uno_C", tau, uno,
                           if (is.finite(uno)) "" else "UNSUPPORTED_IPCW_OR_NO_COMPARABLE_PAIRS"))
    
    for (h in horizons) {
      cases <- which(z$Event == 1L & z$OBS_Days <= h)
      controls <- which(z$OBS_Days > h)
      auc <- brier <- NA_real_
      reason <- ""
      if (h > max_follow) reason <- "HORIZON_BEYOND_TRAINING_FOLLOWUP"
      else if (!length(cases) || !length(controls))
        reason <- "NO_CASES_OR_CONTROLS"
      else {
        gc <- G(km, z$OBS_Days[cases], TRUE, max_follow)
        gn <- G(km, rep(h, length(controls)), FALSE, max_follow)
        if (any(!is.finite(gc) | gc <= 0) ||
            any(!is.finite(gn) | gn <= 0)) reason <- "INVALID_IPCW"
        else {
          wc <- 1 / gc
          wn <- 1 / gn
          pair <- outer(wc, wn)
          greater <- outer(z$Linear_Predictor[cases],
                           z$Linear_Predictor[controls], ">")
          tied <- outer(z$Linear_Predictor[cases],
                        z$Linear_Predictor[controls], "==")
          auc <- sum(pair * (greater + 0.5 * tied)) / sum(pair)
          pred <- z[[paste0("Predicted_Survival_", h)]]
          if (all(is.finite(pred[c(cases, controls)])))
            brier <- (sum(wc * pred[cases]^2) +
                        sum(wn * (1 - pred[controls])^2)) / nrow(z)
          else reason <- "INVALID_SURVIVAL_PREDICTIONS"
        }
      }
      out[[length(out) + 1L]] <- metric_row(f, paste0("AUC_", h), h,
                                            auc, if (is.finite(auc)) "" else reason, length(cases), length(controls))
      out[[length(out) + 1L]] <- metric_row(f, paste0("Brier_", h), h,
                                            brier, if (is.finite(brier)) "" else reason, length(cases), length(controls))
    }
    do.call(rbind, out)
  }
  
  fold_results <- do.call(rbind, lapply(folds, function(f)
    evaluate(oof[oof$Outer_Fold == f, ], censor_models[[as.character(f)]], f)))
  metric_names <- unique(fold_results$Metric)
  summary_metrics <- do.call(rbind, lapply(metric_names, function(m) {
    x <- fold_results[fold_results$Metric == m, ]
    ok <- x$Metric_Status == "ESTIMABLE"
    data.frame(Metric = m, Horizon_Days = x$Horizon_Days[1],
               Estimate = if (all(ok)) mean(x$Estimate) else NA_real_,
               Metric_Status = if (all(ok)) "ESTIMABLE" else "NOT_ESTIMABLE",
               Fold_Estimates_Valid = sum(ok),
               Reason = if (all(ok)) "Equal-weight outer-fold mean"
               else paste(unique(x$Reason[!ok]), collapse = " | "))
  }))
  
  # 7. Fixed-OOF patient bootstrap ------------------------------------------------
  set.seed(20260802)
  boot <- matrix(NA_real_, n_boot, length(metric_names),
                 dimnames = list(NULL, metric_names))
  for (b in seq_len(n_boot)) {
    draws <- lapply(folds, function(f) {
      z <- oof[oof$Outer_Fold == f, ]
      evaluate(z[sample.int(nrow(z), replace = TRUE), ],
               censor_models[[as.character(f)]], f)
    })
    for (m in metric_names) {
      values <- vapply(draws, function(x) {
        row <- x[x$Metric == m, ]
        if (nrow(row) == 1 && row$Metric_Status == "ESTIMABLE")
          row$Estimate else NA_real_
      }, numeric(1))
      if (all(is.finite(values))) boot[b, m] <- mean(values)
    }
  }
  ci <- do.call(rbind, lapply(metric_names, function(m) {
    good <- is.finite(boot[, m])
    accepted <- sum(good) >= min_valid_boot
    data.frame(Metric = m, Bootstrap_Replicates = n_boot,
               Bootstrap_Valid = sum(good), Bootstrap_Invalid = sum(!good),
               CI_Lower = if (accepted) unname(quantile(boot[good, m], 0.025)) else NA_real_,
               CI_Upper = if (accepted) unname(quantile(boot[good, m], 0.975)) else NA_real_,
               CI_Status = if (accepted) "ESTIMABLE" else "NOT_ESTIMABLE")
  }))
  summary_metrics <- merge(summary_metrics, ci, by = "Metric", sort = FALSE)
  summary_metrics$Primary_Status <- ifelse(summary_metrics$Metric != "Uno_C",
                                           "SECONDARY", ifelse(summary_metrics$Metric_Status == "ESTIMABLE",
                                                               "PRIMARY_ESTIMABLE", "PRIMARY_NOT_CONFIRMED"))
  summary_metrics$Patients <- 337L
  summary_metrics$Events <- 179L
  summary_metrics$Censored <- 158L
  summary_metrics$Endpoint <- sap$statistical_analysis_plan$endpoint
  summary_metrics$Time_Origin <- sap$statistical_analysis_plan$time_origin
  summary_metrics$Cox_Tie_Method <- "Efron; not previously specified"
  summary_metrics$External_Validation <- "NOT_PERFORMED"
  
  # 8. Export and verify outputs ---------------------------------------------------
  diagnostic_table <- do.call(rbind, diagnostics)
  pred_columns <- c("Patient_ID", "Sample_ID", "Repeat", "Outer_Fold",
                    "OBS_Days", "Event", "Age_at_Diagnosis_Years", "Sex", "Linear_Predictor",
                    paste0("Predicted_Survival_", rep(horizons, 2),
                           rep(c("", "_Status"), each = length(horizons))))
  oof_export <- oof[, pred_columns, drop = FALSE]
  hashes <- data.frame(Input_File = basename(input_paths),
                       MD5 = unname(tools::md5sum(input_paths)))
  result_object <- list(
    Task = task_id, Author = author_name, Status = "SUCCESS",
    Endpoint = sap$statistical_analysis_plan$endpoint,
    Horizons_Days = horizons, Primary_Tau_Days = tau,
    Formula = "Surv(OBS_Days, Event) ~ Age_at_Diagnosis_Years + Sex",
    Stage_Used = FALSE, Cox_Ties = "efron",
    Fold_Models = models, Fold_Censoring_Models = censor_models,
    OOF_Predictions = oof_export, Fold_Performance = fold_results,
    Performance_Summary = summary_metrics, Cox_Diagnostics = diagnostic_table,
    Bootstrap_Metrics = boot,
    Bootstrap_Rule = list(Replicates = n_boot, Minimum_Valid = min_valid_boot,
                          Method = "Fixed-OOF patient bootstrap, percentile 95% CI"),
    Input_MD5 = hashes,
    External_Validation_Status = "NOT_PERFORMED",
    Clinical_Fitting_Authority = "Project-owner-approved scientific clinical design")
  
  utils::write.csv(summary_metrics, output_paths[["results_csv"]],
                   row.names = FALSE, na = "")
  saveRDS(result_object, output_paths[["results_rds"]], compress = "xz")
  utils::write.csv(oof_export, output_paths[["oof_csv"]],
                   row.names = FALSE, na = "")
  utils::write.csv(fold_results, output_paths[["fold_csv"]],
                   row.names = FALSE, na = "")
  utils::write.csv(diagnostic_table, output_paths[["diagnostics_csv"]],
                   row.names = FALSE, na = "")
  
  data_files <- output_paths[1:5]
  if (any(!file.exists(data_files)) ||
      any(!is.finite(file.info(data_files)$size)) ||
      any(file.info(data_files)$size <= 0))
    stop("A required result file is missing or empty.")
  check_oof <- utils::read.csv(output_paths[["oof_csv"]])
  check_rds <- readRDS(output_paths[["results_rds"]])
  if (nrow(check_oof) != 337 || anyDuplicated(check_oof$Patient_ID) ||
      !identical(check_rds$Task, task_id))
    stop("Exported results failed read-back validation.")
  invisible(utils::read.csv(output_paths[["results_csv"]]))
  invisible(utils::read.csv(output_paths[["fold_csv"]]))
  invisible(utils::read.csv(output_paths[["diagnostics_csv"]]))
  
  task_status <- "SUCCESS"
  message("AUDIT_COMPLETED")
