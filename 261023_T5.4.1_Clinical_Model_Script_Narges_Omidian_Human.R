select_directory <- function(caption) {
  x <- if (requireNamespace("rstudioapi", quietly = TRUE) &&
           rstudioapi::isAvailable()) rstudioapi::selectDirectory(caption)
  else if (.Platform$OS.type == "windows") utils::choose.dir(caption = caption)
  else readline(paste0(caption, ": "))
  if (is.null(x) || length(x) != 1L || is.na(x) ||
      !nzchar(x) || !dir.exists(x)) stop("Invalid directory selection.")
  normalizePath(x, winslash = "/", mustWork = TRUE)
}
redact <- function(x) {
  x <- gsub("[A-Za-z]:[/\\\\][^\\r\\n]*", "[LOCAL_PATH]", x, perl = TRUE)
  gsub("(/Users/|/home/|/var/)[^\\r\\n]*", "[LOCAL_PATH]", x, perl = TRUE)
}
