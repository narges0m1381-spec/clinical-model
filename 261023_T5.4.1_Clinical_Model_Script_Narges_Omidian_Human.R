require_scalar <- function(x, label, minimum = 0) {
  x <- suppressWarnings(as.numeric(unlist(x)))
  if (length(x) != 1L || !is.finite(x) || x < minimum)
    stop("Invalid locked field: ", label, call. = FALSE)
  x
}
metric_row <- function(fold, name, h, estimate = NA_real_,
                       reason = "", cases = NA_integer_, controls = NA_integer_) {
